import assert from 'node:assert/strict';
import {HouseholdPredictiveServo} from '../src/game/household-predictive-servo.js';
import {GroundPickController} from '../src/game/ground-pick-controller.js';
for(const c of [{liftStartPhase:NaN},{liftStartPhase:.29},{liftStartPhase:.51},{liftBlendSeconds:0},{liftBlendSeconds:4},{clampSettleSeconds:.7},{clampSettleSeconds:3}])assert.throws(()=>new GroundPickController(c));
for(const c of [{},{liftStartPhase:.32,liftBlendSeconds:2}])assert.doesNotThrow(()=>new GroundPickController(c));
let plan={ctrl:Array.from({length:14},(_,i)=>i*.01),audit:{sourceStateUnchanged:true}};
const r={head:0,d:{xmat:Float64Array.from([1,0,0,0,1,0,0,0,1]),ctrl:new Float64Array(15),qpos:Float64Array.from([1,2,3]),qfrc_applied:new Float64Array(3)},
  beakClearance:()=>({height:.003}),predictedReachPlan:()=>plan};
const s={graspPoint:[.001,.05,.003],payload:[0,0,.006]},servo=new HouseholdPredictiveServo({});
const before=Array.from(r.d.qpos);
for(let k=0;k<11;k++)servo.apply(r,s);
assert.ok(servo.stable>=.2);
assert.deepEqual(Array.from(r.d.ctrl.slice(0,14)),plan.ctrl);
assert.deepEqual(Array.from(r.d.qpos),before);
assert.ok(r.d.qfrc_applied.every(x=>x===0));
const controls=Array.from(r.d.ctrl);plan={ctrl:[...Array(13).fill(2),NaN]};
assert.throws(()=>servo.apply(r,s));
assert.deepEqual(Array.from(r.d.ctrl),controls,'a late invalid target cannot partly update motors');
plan=null;assert.throws(()=>servo.apply(r,s));
plan={ctrl:Array(14).fill(.1),audit:{},blocked:true};
assert.equal(servo.apply(r,s),false);assert.equal(servo.stable,0);
assert.deepEqual(Array.from(r.d.ctrl),controls,'unsafe forecast must not apply a candidate');
plan={ctrl:Array(14).fill(.1),audit:{}};
const shaftServo=new HouseholdPredictiveServo({kind:'pen',length:.14,axisGrasp:true});
const shaft={graspPoint:[.001,.08,.003],payload:[0,0,.006,1,0,0,0]};
for(let k=0;k<11;k++)shaftServo.apply(r,shaft);
assert.ok(shaftServo.stable>=.2,'an interior shaft grasp need not match the pen center');
shaftServo.apply(r,{...shaft,graspPoint:[.001,.14,.003]});
assert.equal(shaftServo.stable,0,'outside the usable shaft must not count as ready');
const closingServo=new HouseholdPredictiveServo({graspForecast:true});
for(let k=0;k<11;k++)closingServo.apply(r,s);
assert.equal(closingServo.stable,0,'geometric proximity alone cannot pass the optional closure forecast gate');
plan={...plan,graspReady:true};
for(let k=0;k<11;k++)closingServo.apply(r,s);
assert.ok(closingServo.stable>=.2);
closingServo.apply(r,{...s,graspPoint:[.005,.05,.003]});
assert.equal(closingServo.stable,0,'a shallow predicted pinch must still meet the geometric grasp tolerance');
console.log('PASS: predictive servo accepts finite motor targets only; live positions and force inputs remain unchanged');
