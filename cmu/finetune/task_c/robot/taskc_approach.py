class GazeWalkerRule(goal_inputs.GoalEncoder):
    """Steer while advancing and correct a persistent small heading error at the stop."""

    def __init__(self):
        super().__init__()
        self.reset()

    def reset(self):
        super().reset()
        self.turn_side = 0
        self.near_turn_frames = 0

    def encode(self, x, y, stop_d=goal_inputs.STOP_D_DEFAULT):
        (vx, vy, turn), head, arrived = super().encode(x, y, stop_d)
        forward = goal_inputs.clamp(vx / 0.10, 0.0, 1.0)
        gap = abs(math.hypot(x, y) - stop_d)
        side = 0
        if gap <= goal_inputs.ARRIVE_GAP and goal_inputs.ARRIVE_BEARING < abs(turn) < goal_inputs.LEAVE_BEARING:
            side = 1 if turn > 0 else -1
        if side and side == self.turn_side:
            self.near_turn_frames += 1
        else:
            self.near_turn_frames = int(bool(side))
        self.turn_side = side
        # At 8 camera frames/s, wait about one second before asking for the
        # stronger final turn. A passing bearing error often clears in a stride.
        fraction = 1.0 if self.near_turn_frames >= 8 else forward
        turn = goal_inputs.clamp(turn * (1.0 + 1.5 * fraction), -goal_inputs.W_MAX, goal_inputs.W_MAX)
        return (vx, vy, turn), head, arrived


class R8HeadingRule(GazeWalkerRule):
    """Use the heading walker's usual commands until r8 needs its last few steps."""

    odo_gain = 0.4

    def encode(self, x, y, stop_d=goal_inputs.STOP_D_DEFAULT):
        was_stopped = self.arrived
        twist, head, arrived = super().encode(x, y, stop_d)
        gap = math.hypot(x, y) - stop_d
        if gap >= 0.105:
            return twist, head, arrived

        bearing = math.atan2(y, x)
        distance_tolerance = 0.030 if was_stopped else 0.016
        angle_tolerance = 0.40 if was_stopped else 0.25
        self.arrived = abs(gap) < distance_tolerance and abs(bearing) < angle_tolerance
        if self.arrived:
            return (0.0, 0.0, 0.0), head, True
        if abs(bearing) > 0.40 or abs(gap) < 0.016:
            return (0.0, 0.0, math.copysign(0.65, bearing)), head, False

        # Near the ball, the proportional forward request drops below r8's stepping speed.
        # Keep taking steps until the measured range enters the stop band.
        vx = 0.25 if gap > 0 else -goal_inputs.VX_BACK
        return (vx, 0.0, goal_inputs.clamp(2.0 * bearing, -0.5, 0.5)), head, False


