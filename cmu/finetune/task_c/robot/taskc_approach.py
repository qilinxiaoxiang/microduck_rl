class HeadingBallLoop(BallLoop):
    """Hold the camera-derived bearing in the IMU frame while advancing."""

    # Calibrated in the battery-mass simulator with its positive yaw disturbance.
    turn_bias = -1.18
    turn_limit = 1.65
    heading_gain = 3.5
    damping = .45

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.forward_goal = None
        self.turn_integral = self.yaw_rate = 0.0
        self.feedback_t = None
        self.wide_acquisition = None

    def reset_heading(self):
        self.forward_goal = self.feedback_t = None
        self.turn_integral = self.yaw_rate = 0.0

    def send_scan(self, head):
        self.reset_heading()
        super().send_scan(head)

    def send_policy(self, x, y):
        if self.look is None and self.ball_w is not None:
            # A frame is delivered after capture. Use the latest heading to act on it.
            x, y = to_robot(self.ball_w, self.poses[-1][1:])
            if self.wide_acquisition is None:
                # A target outside the forward cone needs a pivot before walking.
                # Choose the gentler steering calibration once, so camera noise
                # around the cone boundary cannot alternate gains across steps.
                self.wide_acquisition = abs(math.atan2(y, x)) > goal_inputs.TURN_ONLY[0]
        twist, head, arrived = self.enc.encode(x, y, self.stop_d)
        absolute_head = {n: self.default[n] + head[i] for i, n in enumerate(HEAD_JOINTS)}
        if self.look is None and twist[0] > .02 and math.hypot(x, y) > .20:
            heading = wrap(self.poses[-1][3] + math.atan2(y, x))
            self.forward_goal = (heading, twist, absolute_head, self.now())
            self.follow_heading()
        else:
            self.reset_heading()
            self.write(twist, absolute_head, "policy")
        return self.twist, head, arrived

    def follow_heading(self):
        heading, (vx, vy, _), head, _ = self.forward_goal
        t, _, _, yaw = self.poses[-1]
        error = wrap(heading - yaw)
        if len(self.poses) >= 2 and t != self.feedback_t:
            prev_t, _, _, prev_yaw = self.poses[-2]
            dt = t - prev_t
            if 0.0 < dt <= .2:
                measured_rate = wrap(yaw - prev_yaw) / dt
                self.yaw_rate += min(1., dt / .09) * (measured_rate - self.yaw_rate)
                self.turn_integral = goal_inputs.clamp(self.turn_integral + 1.2 * dt * error, -.9, .9)
            self.feedback_t = t
        gain, bias, limit = (3.1, -.88, 1.5) if self.wide_acquisition else (
            self.heading_gain, self.turn_bias, self.turn_limit)
        demand = gain * error + self.turn_integral - self.damping * self.yaw_rate + bias
        turn = goal_inputs.clamp(demand, -limit, limit)
        self.write((vx, .6 * vy, turn), head, "policy")

    def step(self):
        previous_frame = self.last_idx
        previous_pose = self.poses[-1] if self.poses else None
        super().step()
        if (self.why or self.kind != "policy" or self.forward_goal is None or self.last_idx != previous_frame
                or not self.poses or self.poses[-1] is previous_pose or self.look is not None):
            return
        # Refresh steering only while the original camera command is live.
        # A stopped camera must still expire the robot's hold-to-walk command.
        age = self.now() - self.forward_goal[3]
        if age >= min(FRAME_MAX_AGE_S, self.for_s or FRAME_MAX_AGE_S):
            self.reset_heading()
            self.write((0., 0., 0.), self.cmd["head"], "policy")
        else:
            self.follow_heading()


