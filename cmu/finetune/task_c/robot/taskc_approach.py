def to_robot(ball_w, pose):
    """Point in the loop's fixed frame -> the floor frame of a robot at pose (x, y, yaw): x forward, y left."""
    dx, dy = ball_w[0] - pose[0], ball_w[1] - pose[1]
    c, s = math.cos(pose[2]), math.sin(pose[2])
    return c * dx + s * dy, -s * dx + c * dy


def to_world(p, pose):
    c, s = math.cos(pose[2]), math.sin(pose[2])
    return pose[0] + c * p[0] - s * p[1], pose[1] + s * p[0] + c * p[1]


